import assert from "node:assert/strict";
import { createRequire } from "node:module";
import test from "node:test";

import { toDockerCompose } from "../src/lib/architecture/export/dockerCompose.ts";

// js-yaml is already installed (through the lint tooling); used here only to prove the output parses.
const yaml = createRequire(import.meta.url)("js-yaml") as { load(text: string): unknown };

const n = (id: string, type: string, extra: Record<string, unknown> = {}) => ({ id, data: { type, label: id, ...extra } }) as never;
const e = (source: string, target: string) => ({ source, target });

const shop = {
  title: "Shop: v2",
  nodes: [
    n("Users", "client"),
    n("CDN", "cdn"),
    n("LB", "load-balancer"),
    n("Orders API", "server", { properties: { replicas: 3 } }),
    n("Worker", "worker", { implementation: "nodejs-worker" }),
    n("Queue", "queue", { implementation: "rabbitmq" }),
    n("Cache", "cache", { implementation: "memcached" }),
    n("Orders DB", "database"),
    n("Users DB", "database", { implementation: "mysql" }),
    n("Files", "object-storage"),
    n("Login", "auth", { implementation: "auth0" }),
    n("Stripe", "custom", { properties: { technology: "Stripe" } }),
  ],
  edges: [
    e("Users", "CDN"), e("CDN", "LB"), e("LB", "Orders API"), e("Orders API", "Cache"), e("Orders API", "Orders DB"),
    e("Orders API", "Users DB"), e("Orders API", "Queue"), e("Queue", "Worker"), e("Worker", "Orders DB"),
    e("Orders API", "Files"), e("Orders API", "Login"), e("Orders API", "Stripe"),
  ],
};

type Compose = { services: Record<string, { image?: string; build?: string; ports?: string[]; environment?: Record<string, string>; depends_on?: string[]; deploy?: { replicas: number }; volumes?: string[] }>; volumes?: Record<string, unknown> };

test("a design becomes a valid docker-compose file that follows its connections", () => {
  const result = toDockerCompose(shop, new Date("2026-10-19T00:00:00Z"));
  const compose = yaml.load(result.yaml) as Compose;
  const s = compose.services;
  assert.deepEqual(Object.keys(s).sort(), ["cache", "files", "lb", "orders-api", "orders-db", "queue", "users-db", "worker"]);
  assert.equal(s.lb.image, "nginx:1.27-alpine");
  assert.deepEqual(s.lb.ports, ["8080:80"], "the entry (behind the CDN) is published");
  assert.deepEqual(s.lb.depends_on, ["orders-api"]);
  assert.equal(s["orders-api"].build, "./orders-api");
  assert.equal(s["orders-api"].deploy?.replicas, 3);
  assert.equal(s["orders-api"].environment?.MEMCACHED_SERVERS, "cache:11211");
  // Two databases of a kind would get suffixes; here Postgres and MySQL both use DATABASE_URL.
  assert.equal(s["orders-api"].environment?.DATABASE_URL_ORDERS_DB, "postgresql://app:app@orders-db:5432/app");
  assert.equal(s["orders-api"].environment?.DATABASE_URL_USERS_DB, "mysql://app:app@users-db:3306/app");
  assert.deepEqual(s.worker.depends_on?.sort(), ["orders-db", "queue"], "a worker depends on the queue that feeds it");
  assert.equal(s.queue.depends_on, undefined, "data services depend on nothing");
  assert.equal(s["users-db"].image, "mysql:8.4");
  assert.ok(compose.volumes && "orders-db-data" in compose.volumes);
  assert.deepEqual(result.skipped.map((item) => item.label), ["Login", "Stripe"]);
  assert.match(result.yaml, /^# docker-compose\.yml for "Shop: v2", generated by ARCHITECH on 2026-10-19\./);
});

test("names are unique and safe; an empty design still parses", () => {
  const twins = toDockerCompose({ title: "x", nodes: [n("API!", "server"), n("api", "server")], edges: [] });
  assert.deepEqual(twins.services, ["api", "api-2"]);
  const empty = toDockerCompose({ title: "Nothing", nodes: [n("Users", "client")], edges: [] });
  assert.deepEqual((yaml.load(empty.yaml) as Compose).services, {});
});
